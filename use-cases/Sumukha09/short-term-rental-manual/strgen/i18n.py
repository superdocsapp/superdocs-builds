class T:
    """Tiny translator bound to one language with graceful fallback to English."""

    def __init__(self, lang: str, base_lang: str = "en"):
        self.lang = lang if lang in STRINGS else "en"
        self.base_lang = base_lang if base_lang in STRINGS else "en"

    def __call__(self, key: str) -> str:
        return STRINGS[self.lang].get(key) or STRINGS["en"].get(key) or key

    def month_year(self, year: int, month: int) -> str:
        months = _MONTHS.get(self.lang, _MONTHS["en"])
        return f"{months[month - 1]} {year}"
