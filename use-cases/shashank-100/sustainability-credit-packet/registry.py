"""The credit register: the single source of truth for the packet.

Two rules hold this module together, both taken from the card's grading
criteria:

1. Status is *derived*, never authored. A credit is "documented" only when
   every evidence item it declares is genuinely present in the bundle. Nobody
   can mark a credit complete by editing a field.

2. The evidence index is generated by looking at the filesystem, so it cannot
   drift from what is really in the bundle. The card is graded on the index
   matching reality; a hand-maintained list would be a lie waiting to happen.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from pathlib import Path

import yaml

import calc

# A credit's status. "at_risk" is an explicit human judgement, applied over the
# derived status -- a team can know a credit is in trouble before its evidence
# goes missing.
DOCUMENTED = "documented"
EVIDENCE_OUTSTANDING = "evidence outstanding"
AT_RISK = "at risk"

STATUSES = (DOCUMENTED, EVIDENCE_OUTSTANDING, AT_RISK)


@dataclass(frozen=True)
class EvidenceItem:
    description: str
    file: str
    present: bool
    location: str  # where it lives in the bundle, or why it does not

    @property
    def marker(self) -> str:
        return "present" if self.present else "MISSING"


@dataclass(frozen=True)
class Credit:
    id: str
    name: str
    category: str
    points_targeted: int
    requirement_file: str
    evidence: list[EvidenceItem]
    result: calc.CalcResult
    override: str | None = None  # human-set status, e.g. "at risk"

    @property
    def missing_evidence(self) -> list[EvidenceItem]:
        return [e for e in self.evidence if not e.present]

    @property
    def status(self) -> str:
        """Derived from evidence, unless a human has flagged it at risk."""
        if self.override:
            return self.override
        return EVIDENCE_OUTSTANDING if self.missing_evidence else DOCUMENTED

    @property
    def points_awarded(self) -> int:
        """Points only count when the credit is fully documented.

        A credit whose evidence is incomplete cannot be claimed, so it
        contributes nothing to the scorecard total. This is what makes a status
        change move the total.
        """
        return self.result.points if self.status == DOCUMENTED else 0

    @property
    def requirement_text(self) -> str:
        return Path(self.requirement_file).read_text(encoding="utf-8")


@dataclass(frozen=True)
class Scorecard:
    """The cover. Every figure here is computed, never written by a model."""

    project: dict
    credits: list[Credit]

    @property
    def points_awarded(self) -> int:
        return sum(c.points_awarded for c in self.credits)

    @property
    def points_targeted(self) -> int:
        return sum(c.points_targeted for c in self.credits)

    @property
    def points_at_risk(self) -> int:
        return sum(c.result.points for c in self.credits if c.status != DOCUMENTED)

    @property
    def level(self) -> str:
        return calc.certification_level(self.points_awarded)

    @property
    def target_level(self) -> str:
        return self.project.get("target_level", "Gold")

    @property
    def meets_target(self) -> bool:
        bands = dict((lvl, pts) for pts, lvl in calc.CERTIFICATION_BANDS)
        return self.points_awarded >= bands.get(self.target_level, 60)

    @property
    def shortfall_to_target(self) -> int:
        bands = dict((lvl, pts) for pts, lvl in calc.CERTIFICATION_BANDS)
        return max(0, bands.get(self.target_level, 60) - self.points_awarded)

    def by_status(self, status: str) -> list[Credit]:
        return [c for c in self.credits if c.status == status]

    def credit(self, credit_id: str) -> Credit:
        for c in self.credits:
            if c.id == credit_id:
                return c
        raise KeyError(f"no credit {credit_id!r} in the register")


def _resolve_evidence(spec: dict, corpus: Path) -> EvidenceItem:
    """Check the bundle for one evidence item. The filesystem is the authority."""
    path = corpus / spec["file"]
    present = path.is_file()
    return EvidenceItem(
        description=spec["description"],
        file=spec["file"],
        present=present,
        location=str(path) if present else "not in bundle",
    )


def _run_calculation(spec: dict, corpus: Path) -> calc.CalcResult:
    """Dispatch to the named function in calc, resolving path arguments."""
    function = getattr(calc, spec["function"])
    args = {}
    for key, value in spec.get("args", {}).items():
        args[key] = corpus / value if key.endswith("_csv") else value
    return function(**args)


def load(config_path: Path | str, root: Path | None = None) -> Scorecard:
    """Build the scorecard from the register plus what is really in the bundle."""
    config_path = Path(config_path)
    root = root or config_path.parent
    config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    corpus = root / config["project"]["corpus"]

    credits = []
    for spec in config["credits"]:
        credits.append(
            Credit(
                id=spec["id"],
                name=spec["name"],
                category=spec["category"],
                points_targeted=spec["points_targeted"],
                requirement_file=str(root / spec["requirement_file"]),
                evidence=[_resolve_evidence(e, corpus) for e in spec["evidence"]],
                result=_run_calculation(spec["calculation"], corpus),
            )
        )
    return Scorecard(project=config["project"], credits=credits)


def set_status(scorecard: Scorecard, credit_id: str, status: str) -> Scorecard:
    """Return a new scorecard with one credit's status overridden.

    Returns a fresh object rather than mutating: the caller needs the before
    and after to compute what changed, and an immutable scorecard cannot drift
    from the documents generated from it.
    """
    if status not in STATUSES:
        raise ValueError(f"unknown status {status!r}, expected one of {STATUSES}")

    target = scorecard.credit(credit_id)
    if status == DOCUMENTED and target.missing_evidence:
        missing = ", ".join(e.file for e in target.missing_evidence)
        raise ValueError(
            f"cannot mark {credit_id} documented while evidence is missing: {missing}"
        )

    # Clearing the override restores the derived status. DOCUMENTED clears it
    # for a complete credit; EVIDENCE_OUTSTANDING clears it for one whose
    # evidence is incomplete, which DOCUMENTED cannot do -- without this a
    # credit flagged at risk could never be un-flagged, because the only route
    # back is barred by the missing evidence that prompted the flag.
    if status == EVIDENCE_OUTSTANDING and target.missing_evidence:
        override = None
    else:
        override = None if status == DOCUMENTED else status
    updated = [replace(c, override=override) if c.id == credit_id else c for c in scorecard.credits]
    return replace(scorecard, credits=updated)
