def render_document_html(doc_key: str) -> str:
    """Wrap each chunk of DOCUMENTS[doc_key] in <div data-chunk-id="..."> and join."""
    doc = DOCUMENTS[doc_key]
    parts = []
    for chunk in doc["chunks"]:
        parts.append(f'<div data-chunk-id="{chunk["chunk_id"]}">{chunk["body_html"]}</div>')
    return "\n".join(parts)

