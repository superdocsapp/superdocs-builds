"""Markdown document model.

Splits a document into the scopes the rubric's detectors are defined over.
Deliberately minimal: no markdown library, no AST. The corpus is generated by
this repo, so the surface it has to handle is known and small.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

_FENCE = re.compile(r"^\s*```")
_HEADING = re.compile(r"^(#{1,6})\s+(.*)$")
_LIST_ITEM = re.compile(r"^\s*(?:[-*+]|\d+\.)\s+(.*)$")
_INLINE_CODE = re.compile(r"`[^`]*`")

# Sentence splitting. Abbreviations that must not end a sentence.
_ABBREV = {
    "e.g.", "i.e.", "etc.", "cf.", "vs.", "Mr.", "Mrs.", "Ms.", "Dr.", "Prof.",
    "Inc.", "Ltd.", "Co.", "No.", "Fig.", "St.", "Jr.", "Sr.", "approx.",
}
_SENT_BOUNDARY = re.compile(r"(?<=[.!?])[\"')\]]?\s+")


def split_sentences(text: str) -> list[str]:
    """Split prose into sentences, honouring an abbreviation exception list."""
    if not text.strip():
        return []
    pieces = _SENT_BOUNDARY.split(text.strip())
    out: list[str] = []
    for piece in pieces:
        piece = piece.strip()
        if not piece:
            continue
        if out:
            last_token = out[-1].split()[-1] if out[-1].split() else ""
            if last_token in _ABBREV:
                out[-1] = out[-1] + " " + piece
                continue
        out.append(piece)
    return out


def word_count(sentence: str) -> int:
    """Whitespace-delimited tokens containing at least one alphanumeric char."""
    return sum(1 for t in sentence.split() if re.search(r"[0-9A-Za-z]", t))


@dataclass
class Document:
    """A parsed document exposing the scopes detectors are defined over."""

    raw: str
    headings: list[str] = field(default_factory=list)
    list_items: list[str] = field(default_factory=list)
    paragraphs: list[str] = field(default_factory=list)
    tables: list[str] = field(default_factory=list)
    code: list[str] = field(default_factory=list)

    @classmethod
    def parse(cls, raw: str) -> "Document":
        doc = cls(raw=raw)
        in_fence = False
        para: list[str] = []

        def flush() -> None:
            if para:
                doc.paragraphs.append(" ".join(para).strip())
                para.clear()

        for line in raw.splitlines():
            if _FENCE.match(line):
                flush()
                in_fence = not in_fence
                continue
            if in_fence:
                doc.code.append(line)
                continue
            stripped = line.strip()
            if not stripped:
                flush()
                continue
            if stripped.startswith("|"):
                flush()
                doc.tables.append(stripped)
                continue
            m = _HEADING.match(line)
            if m:
                flush()
                doc.headings.append(_strip_inline_code(m.group(2).strip()))
                continue
            m = _LIST_ITEM.match(line)
            if m:
                flush()
                doc.list_items.append(_strip_inline_code(m.group(1).strip()))
                continue
            para.append(_strip_inline_code(stripped))
        flush()
        return doc

    # --- scopes -----------------------------------------------------------

    @property
    def prose_segments(self) -> list[str]:
        """Paragraphs and list items. Excludes headings, tables, code."""
        return list(self.paragraphs) + list(self.list_items)

    @property
    def body_segments(self) -> list[str]:
        """Everything a reader reads: headings, paragraphs, list items."""
        return list(self.headings) + list(self.paragraphs) + list(self.list_items)

    @property
    def prose_text(self) -> str:
        return "\n".join(self.prose_segments)

    @property
    def body_text(self) -> str:
        return "\n".join(self.body_segments)

    @property
    def paragraph_sentences(self) -> list[str]:
        out: list[str] = []
        for p in self.paragraphs:
            out.extend(split_sentences(p))
        return out


def _strip_inline_code(text: str) -> str:
    return _INLINE_CODE.sub(" ", text)
