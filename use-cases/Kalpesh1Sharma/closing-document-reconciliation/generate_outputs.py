import json
from pathlib import Path

from docx import Document

from core.corrections import (
    render_correction_request,
)
from core.memo import (
    render_reconciliation_memo,
)


REPORT_PATH = Path(
    "outputs/scenario_a_reconciliation.json"
)

OUTPUT_DIR = Path("outputs")

MEMO_MD = OUTPUT_DIR / (
    "scenario_a_reconciliation_memo.md"
)

CORRECTION_MD = OUTPUT_DIR / (
    "scenario_a_revised_disclosure_request.md"
)

MEMO_DOCX = OUTPUT_DIR / (
    "scenario_a_reconciliation_memo.docx"
)

CORRECTION_DOCX = OUTPUT_DIR / (
    "scenario_a_revised_disclosure_request.docx"
)


def markdown_to_docx(
    markdown_text: str,
    output_path: Path,
) -> None:
    """
    Small deterministic Markdown-to-DOCX renderer for
    the subset generated by our own templates.
    """

    document = Document()

    for raw_line in markdown_text.splitlines():
        line = raw_line.strip()

        if not line:
            document.add_paragraph()
            continue

        if line == "---":
            document.add_paragraph(
                "────────────────────────────"
            )
            continue

        if line.startswith("# "):
            document.add_heading(
                line[2:],
                level=1,
            )
            continue

        if line.startswith("## "):
            document.add_heading(
                line[3:],
                level=2,
            )
            continue

        if line.startswith("### "):
            document.add_heading(
                line[4:],
                level=3,
            )
            continue

        if line.startswith("- "):
            document.add_paragraph(
                line[2:],
                style="List Bullet",
            )
            continue

        if line.startswith("  - "):
            document.add_paragraph(
                line[4:],
                style="List Bullet 2",
            )
            continue

        # Keep Markdown bold markers as text for now.
        # SuperDocs can later perform presentation editing
        # during the review/edit stage.
        document.add_paragraph(
            line
        )

    document.save(
        output_path
    )


def main() -> None:
    if not REPORT_PATH.exists():
        raise FileNotFoundError(
            (
                "Reconciliation report not found. "
                "Run python run_scenario_a.py first."
            )
        )

    report = json.loads(
        REPORT_PATH.read_text(
            encoding="utf-8"
        )
    )

    memo = render_reconciliation_memo(
        report
    )

    correction_request = (
        render_correction_request(
            report
        )
    )

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    MEMO_MD.write_text(
        memo,
        encoding="utf-8",
    )

    CORRECTION_MD.write_text(
        correction_request,
        encoding="utf-8",
    )

    markdown_to_docx(
        memo,
        MEMO_DOCX,
    )

    markdown_to_docx(
        correction_request,
        CORRECTION_DOCX,
    )

    print(
        "Grounded output generation complete."
    )

    print()

    print("Created:")

    for path in [
        MEMO_MD,
        CORRECTION_MD,
        MEMO_DOCX,
        CORRECTION_DOCX,
    ]:
        print(
            f"  ✓ {path}"
        )

    curable_count = sum(
        1
        for finding in report.get(
            "findings",
            [],
        )
        if finding.get(
            "classification"
        ) == "curable"
    )

    tolerable_count = sum(
        1
        for finding in report.get(
            "findings",
            [],
        )
        if finding.get(
            "classification"
        ) == "tolerable"
    )

    print()

    print(
        f"Curable findings included in "
        f"correction request: {curable_count}"
    )

    print(
        f"Tolerable findings excluded from "
        f"correction request: {tolerable_count}"
    )

    print()

    print(
        "No SuperDocs API call was made."
    )


if __name__ == "__main__":
    main()