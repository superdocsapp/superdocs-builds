from __future__ import annotations

import re
import tempfile
from pathlib import Path

from docx import Document


# The memo generator intentionally emits only a small Markdown subset.
# Keep the DOCX renderer equally small and deterministic.
_INLINE_PATTERN = re.compile(
    r"(\*\*.+?\*\*|_\(.+?\)_)",
)


def _add_inline_markdown(
    paragraph,
    text: str,
) -> None:
    """
    Render the inline Markdown produced by this project.

    Supported:
    - **bold**
    - _(source-value style italics)_

    Everything else is written literally. This is deliberately not a
    general-purpose Markdown renderer.
    """

    cursor = 0

    for match in _INLINE_PATTERN.finditer(text):
        if match.start() > cursor:
            paragraph.add_run(
                text[cursor:match.start()]
            )

        token = match.group(0)

        if token.startswith("**"):
            run = paragraph.add_run(
                token[2:-2]
            )
            run.bold = True

        else:
            # The generated memo uses _(source value: ...)_.
            run = paragraph.add_run(
                token[1:-1]
            )
            run.italic = True

        cursor = match.end()

    if cursor < len(text):
        paragraph.add_run(
            text[cursor:]
        )


def markdown_to_docx_bytes(
    markdown_text: str,
) -> bytes:
    """
    Render the small Markdown subset generated by this app into DOCX.

    Block syntax:
    - # / ## / ### headings
    - "- " bullet items
    - "---" separator

    Inline syntax:
    - **bold**
    - _(source-value style italics)_
    """

    with tempfile.TemporaryDirectory() as temp_dir:
        output_path = (
            Path(temp_dir)
            / "generated.docx"
        )

        document = Document()

        for raw_line in markdown_text.splitlines():
            line = raw_line.strip()

            if not line:
                document.add_paragraph()
                continue

            if line == "---":
                document.add_paragraph(
                    "────────────────────────────"
                )
                continue

            if line.startswith("# "):
                paragraph = document.add_heading(
                    level=1,
                )
                _add_inline_markdown(
                    paragraph,
                    line[2:],
                )
                continue

            if line.startswith("## "):
                paragraph = document.add_heading(
                    level=2,
                )
                _add_inline_markdown(
                    paragraph,
                    line[3:],
                )
                continue

            if line.startswith("### "):
                paragraph = document.add_heading(
                    level=3,
                )
                _add_inline_markdown(
                    paragraph,
                    line[4:],
                )
                continue

            if line.startswith("- "):
                paragraph = document.add_paragraph(
                    style="List Bullet",
                )
                _add_inline_markdown(
                    paragraph,
                    line[2:],
                )
                continue

            paragraph = document.add_paragraph()
            _add_inline_markdown(
                paragraph,
                line,
            )

        document.save(
            output_path
        )

        return output_path.read_bytes()
