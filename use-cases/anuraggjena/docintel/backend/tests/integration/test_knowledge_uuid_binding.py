"""Integration test to verify Knowledge API handles UUIDs correctly and doesn't cause PostgreSQL type mismatch errors."""
import pytest
from uuid import uuid4
from httpx import AsyncClient, ASGITransport

from backend.main import app
from backend.database import get_db
from backend.models.knowledge import KnowledgeEntry
from backend.models.workspace import Workspace
from backend.models.user import User


@pytest.mark.asyncio
async def test_knowledge_repository_query_generates_correct_sql(db_session):
    """
    Regression test for P0 bug: PostgreSQL error 'operator does not exist: uuid = character varying'

    This integration test verifies that the actual SQL generated by SQLAlchemy
    binds workspace_id as UUID, not VARCHAR, when querying knowledge_entries.

    The bug was caused by:
    - Database column: knowledge_entries.workspace_id UUID
    - ORM model: workspace_id = Column(String, ...)

    SQLAlchemy bound workspace_id as VARCHAR, causing PostgreSQL error:
    "operator does not exist: uuid = character varying"

    Fix: Changed model to use Column(UUID(as_uuid=True), ...)
    """
    from backend.repositories.knowledge import KnowledgeRepository

    session = db_session

    # Create test user first
    user_id = uuid4()
    user = User(
        id=user_id,
        email=f"uuid-test-{user_id}@example.com",
        password_hash="$2b$12$fakehashfakehashfakehashfakehashfakehashfakehashfake",
        name="UUID Test User"
    )
    session.add(user)
    await session.commit()

    # Create test workspace
    workspace_id = uuid4()
    workspace = Workspace(
        id=workspace_id,
        name="UUID Binding Test Workspace",
        owner_user_id=user_id
    )
    session.add(workspace)
    await session.commit()

    repo = KnowledgeRepository(session)

    # This query should generate SQL with UUID binding for workspace_id:
    # WHERE knowledge_entries.workspace_id = $1::UUID
    # NOT: WHERE knowledge_entries.workspace_id = $1::VARCHAR
    #
    # If the model is correctly defined as UUID(as_uuid=True), this will succeed.
    # If incorrectly defined as String, PostgreSQL will raise:
    # "operator does not exist: uuid = character varying"
    result = await repo.list_by_workspace_and_type(
        workspace_id=workspace_id,
        workflow_type="tariff_classification",
        limit=10
    )

    # If no PostgreSQL error occurred, the UUID binding is correct
    assert isinstance(result, list)
