"""Half two: the readiness pack, built from the same register.

## Why this is not optional

At a single document, an AI edit that fixes `80%` to `90%` saves twenty seconds
and SuperDocs is barely earning its place. It earns it at estate scale, in
multi-document consistency, and here. **Without half two this is a linter with a
nice UI.**

The difference is what the two halves are *for*. The reconciler answers "is this
page true", one passage at a time, to an engineer who is about to follow it. The
pack answers "can this team take the pager on Monday" and "show me the evidence
this estate can be recovered", to a manager and to an auditor, from the same
rows. Neither is a report generated by asking a model to write about
infrastructure: every line traces to a claim in the register and a file in the
estate, and the lines that could not be verified say so in the document rather
than being quietly dropped.

## Two documents, and the rail between them

**On-call readiness** — per service: is there a runbook, is it verified, when
was it last checked, what does nobody check. Plus the coverage numbers and the
orphans on both sides.

**DR evidence** — auditor-facing: what the estate declares about backups,
retention and recovery objectives, which of those a runbook repeats, and which
of the repetitions are true. Its most important column is the one holding
`unverifiable`, because an evidence document that silently drops what it could
not check is worse than no evidence document.

The rail, from the non-goals: **no claimed certifications.** SOC 2 and ISO are
the buyer's motivation, never our claim. This produces evidence a human submits;
it does not assert compliance, and `test_pack.py` asserts that neither document
ever contains the words.

## Multi-document consistency

The same threshold appears in the runbook, the SLO document and the DR plan, and
they drift apart from each other rather than from the infrastructure. Because
every claim in the register carries its subject, that is a `GROUP BY subject
HAVING COUNT(DISTINCT asserted) > 1` — the register was designed for this at
stage 2 rather than the pack reaching back for it now. It is reported, never
auto-resolved: which of three spellings is right is a judgement, and the tool's
job is to put the three in front of somebody.

## Export

`export` is free, so the pack leans on it: the HTML is generated here, uploaded
as a document and exported as PDF or DOCX through SuperDocs' own renderer and
house template. The offline path produces the same HTML without a key, because
a readiness report that needs an API key to be read is a readiness report nobody
reads.
"""

from __future__ import annotations

import html
from collections.abc import Iterable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from reconciler.check.coverage import Coverage
from reconciler.claims import Claim
from reconciler.estate import Estate
from reconciler.register import Register

#: Words this project does not get to say about itself. See the module
#: docstring: certification is the buyer's motivation, never our claim.
FORBIDDEN_CLAIMS = ("SOC 2", "SOC2", "ISO 27001", "certified", "compliant")


@dataclass(frozen=True)
class ServiceRow:
    """One service's readiness, and the evidence behind each column."""

    service: str
    tier: str = ""
    owner: str = ""
    escalation: str = ""
    runbook_pages: tuple[str, ...] = ()
    claims: int = 0
    verified: int = 0
    contradicted: int = 0
    unverifiable: int = 0
    alerts: int = 0
    alerts_with_runbook: int = 0

    @property
    def status(self) -> str:
        """Deliberately three words, and `unknown` is one of them.

        A readiness report whose worst state is "needs attention" cannot say the
        thing a manager most needs to hear, which is that nobody has any idea.
        """
        if not self.runbook_pages:
            return "no runbook"
        if self.contradicted:
            return "drift"
        if self.verified and not self.unverifiable:
            return "verified"
        if self.verified:
            return "partly verified"
        return "unknown"


@dataclass(frozen=True)
class Divergence:
    """One subject asserted differently in more than one document."""

    subject: str
    #: `(page_id, asserted)`, one per spelling.
    spellings: tuple[tuple[str, str], ...]

    @property
    def pages(self) -> tuple[str, ...]:
        return tuple(sorted({page for page, _ in self.spellings}))


@dataclass
class Pack:
    """A document, as content plus the numbers it was built from."""

    title: str
    subtitle: str = ""
    html: str = ""
    rows: tuple[ServiceRow, ...] = ()
    divergences: tuple[Divergence, ...] = ()
    notes: tuple[str, ...] = ()
    generated_at: str = ""

    def write(self, directory: Path, name: str) -> Path:
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"{name}.html"
        path.write_text(self.html, encoding="utf-8")
        return path


# --------------------------------------------------------------- gathering --


def service_rows(register: Register, estate: Estate) -> list[ServiceRow]:
    """One row per catalogued component, joined to the register two ways.

    **By subject and by page, and the page half is not optional.** Joining on
    the subject alone looked right and was quietly wrong: the drift on
    `payments-api`'s runbook is recorded under the subject
    `alert:PaymentsApiHighLatency:threshold`, which contains the service's name
    nowhere. The first version of this table therefore reported `payments-api`
    as *verified* while its runbook carried a live contradiction — a readiness
    report reassuring somebody about the one service that needed attention,
    which is worse than having no report.

    So a finding also belongs to a service when it sits on a page this
    service's claims are on. That relation is already established, deterministic
    and the same one the coverage join uses.
    """
    rows: list[ServiceRow] = []
    for component in sorted(estate.components, key=lambda c: c.name):
        claims = _claims_about(register, component.names)
        pages = tuple(sorted({claim.page_id for claim in claims if claim.page_id}))
        by_id = {
            f.finding_id: f for name in component.names for f in register.findings(subject=name)
        }
        for page_id in pages:
            for finding in register.findings(page_id=page_id):
                by_id[finding.finding_id] = finding
        findings = list(by_id.values())
        alerts = _alerts_for(estate, component, pages)
        rows.append(
            ServiceRow(
                service=component.name,
                tier=component.tier or "",
                owner=component.owner or "",
                escalation=component.escalation_policy or "",
                runbook_pages=pages,
                claims=len(claims),
                verified=sum(1 for f in findings if f.verdict == "agrees"),
                contradicted=sum(1 for f in findings if f.verdict == "contradicts"),
                unverifiable=sum(1 for f in findings if f.verdict == "unverifiable"),
                alerts=len(alerts),
                alerts_with_runbook=sum(1 for a in alerts if a.runbook_page_id),
            )
        )
    return rows


def _alerts_for(estate: Estate, component: Any, pages: tuple[str, ...]) -> list[Any]:
    """Alerts belonging to a service, by links that actually exist.

    An `AlertRule` has no service field, and inventing one by matching the
    alert's name or its PromQL against the service's name is exactly the fuzzy
    resolution `estate.py` refuses to do — it would attribute
    `PaymentsApiHighLatency` to a service called `api` and be wrong in a way
    nobody notices until the readiness report is used to staff a rota.

    So two deterministic routes only: the alert's `runbook_url` annotation
    points at one of this service's runbook pages, or its `team` label is this
    service's catalog owner. An alert reachable by neither is counted in the
    estate-wide coverage numbers and in no service's row, which is honest —
    unattributed is a real state and the coverage section is where it shows up.
    """
    owner = (component.owner or "").strip().lower()
    out = []
    for alert in estate.alerts:
        page = alert.runbook_page_id
        by_runbook = bool(page and page in pages)
        by_team = bool(owner and (alert.team or "").strip().lower() == owner)
        if by_runbook or by_team:
            out.append(alert)
    return out


def _claims_about(register: Register, names: Iterable[str]) -> list[Claim]:
    seen: dict[str, Claim] = {}
    for name in names:
        for claim in register.claims_like(name):
            seen[claim.claim_id] = claim
    return list(seen.values())


def divergences(register: Register) -> list[Divergence]:
    """Subjects two documents disagree about — regardless of which is right.

    Note what this does *not* consult: the estate. Two pages contradicting each
    other is worth surfacing even when neither can be checked against anything,
    and it is the one class of problem the vertical checker structurally cannot
    see.
    """
    out: list[Divergence] = []
    for subject, spellings in register.subjects_with_conflicting_assertions().items():
        out.append(Divergence(subject=subject, spellings=tuple(spellings)))
    return sorted(out, key=lambda d: d.subject)


# ------------------------------------------------------------- the documents --


def build_readiness(
    register: Register,
    estate: Estate,
    coverage: Coverage | None = None,
    generated_at: str | None = None,
) -> Pack:
    """Can this team take the pager on Monday, and on what evidence."""
    rows = service_rows(register, estate)
    diverged = divergences(register)
    summary = register.summary()
    when = generated_at or _now()

    body = [
        _h1("On-call readiness"),
        _p(
            f"Generated {html.escape(when)} from the claim register. Every row below traces "
            f"to a claim extracted from a runbook and checked against a file in the "
            f"infrastructure repositories; nothing here is inferred."
        ),
        _h2("Where the estate stands"),
        _stat_table(
            [
                ("Services in the catalog", str(len(rows))),
                ("Services with a runbook", str(sum(1 for r in rows if r.runbook_pages))),
                ("Services with drift", str(sum(1 for r in rows if r.status == "drift"))),
                ("Claims checked", str(summary["claims"])),
                ("Claims that agree with the estate", str(summary["agrees"])),
                ("Claims that contradict it", str(summary["contradicts"])),
                ("Claims nobody could check", str(summary["unverifiable"])),
            ]
        ),
    ]

    if coverage:
        body += [
            _h2("Alert coverage"),
            _p(html.escape(coverage.headline())),
        ]
        if coverage.orphan_runbook_pages:
            body.append(
                _p(
                    "Runbook pages describing something that no longer exists: "
                    + ", ".join(html.escape(p) for p in coverage.orphan_runbook_pages)
                )
            )

    body += [
        _h2("Service by service"),
        _table(
            [
                "Service",
                "Tier",
                "Owner",
                "On-call",
                "Runbook",
                "Verified",
                "Drift",
                "Unchecked",
                "Status",
            ],
            [
                [
                    row.service,
                    row.tier or "—",
                    row.owner or "—",
                    row.escalation or "—",
                    ", ".join(row.runbook_pages) or "none",
                    str(row.verified),
                    str(row.contradicted),
                    str(row.unverifiable),
                    row.status,
                ]
                for row in rows
            ],
        ),
        _h2("What nobody is checking"),
        _p(
            f"{summary['unverifiable']} claim(s) could not be checked against anything in the "
            f"declared configuration. They are counted here rather than folded into the "
            f"verified column: a claim this tool could not check is reported as unchecked, "
            f"never as correct."
        ),
    ]

    shared = register.multi_page_subjects()
    if shared:
        body += [
            _h2("Facts documented in more than one place"),
            _p(
                f"{len(shared)} subject(s) appear on more than one page. "
                f"{len(shared) - len(diverged)} of them agree everywhere they are stated; "
                f"{len(diverged)} do not. This is the check no single-document review "
                f"performs: a page can be internally consistent, correct against the "
                f"estate, and still contradict the page next to it."
            ),
        ]

    if diverged:
        body += [
            _h2("Documents that disagree with each other"),
            _p(
                "The same subject, asserted differently in more than one document. "
                "Which spelling is right is a judgement, so these are listed rather "
                "than resolved."
            ),
            _table(
                ["Subject", "Says"],
                [
                    [
                        d.subject,
                        "; ".join(f"page {page}: {value}" for page, value in d.spellings),
                    ]
                    for d in diverged
                ],
            ),
        ]

    body.append(_limits())
    return Pack(
        title="On-call readiness",
        subtitle=f"generated {when}",
        html=_document("On-call readiness", body),
        rows=tuple(rows),
        divergences=tuple(diverged),
        generated_at=when,
    )


def build_dr_evidence(
    register: Register,
    estate: Estate,
    generated_at: str | None = None,
) -> Pack:
    """What an auditor asks for: the claim, the evidence, and the gaps.

    The gaps are the point. An evidence pack that lists only what it could prove
    is a sales document; this one lists what it could not, with the same weight.
    """
    when = generated_at or _now()
    measures = _recovery_measures(register, estate)
    unchecked = [m for m in measures if m["verdict"] == "unverifiable"]
    contradicted = [m for m in measures if m["verdict"] == "contradicts"]

    body = [
        _h1("Disaster recovery evidence"),
        _p(
            f"Generated {html.escape(when)} from the claim register. This document reports "
            f"what the infrastructure repositories declare about backup and recovery, and "
            f"whether the operational documentation repeats it correctly."
        ),
        _p(
            "<strong>What this is not.</strong> It is evidence for a human to submit, not "
            "an assertion about any standard. It covers configuration declared in git, not "
            "the running state of any cloud account, and it says nothing about whether a "
            "recovery has ever been rehearsed."
        ),
        _h2("Recovery measures found in the estate"),
        _table(
            ["Measure", "The estate declares", "A runbook says", "Checked", "Evidence"],
            [
                [
                    m["subject"],
                    m["observed"] or "—",
                    m["asserted"] or "not documented",
                    m["verdict"],
                    m["evidence"],
                ]
                for m in measures
            ],
        ),
    ]

    if contradicted:
        body += [
            _h2("Documentation that disagrees with the estate"),
            _p(
                f"{len(contradicted)} recovery claim(s) in the documentation do not match "
                f"what the infrastructure declares. Each is a passage awaiting review."
            ),
        ]

    body += [
        _h2("What this evidence does not cover"),
        _p(
            f"{len(unchecked)} measure(s) could not be checked against anything in the "
            f"declared configuration. Listed here in full, because an evidence document "
            f"that omits its own gaps is worse than no evidence document."
        ),
        _list([f"{m['subject']}: {m['detail']}" for m in unchecked] or ["None."]),
        _limits(),
    ]
    return Pack(
        title="Disaster recovery evidence",
        subtitle=f"generated {when}",
        html=_document("Disaster recovery evidence", body),
        generated_at=when,
    )


def _recovery_measures(register: Register, estate: Estate) -> list[dict[str, str]]:
    """Backup, retention and recovery claims, joined to their findings."""
    out: list[dict[str, str]] = []
    for finding in register.findings():
        if finding.kind not in {"measure", "retention", "schedule", "threshold"}:
            continue
        if not any(
            word in finding.subject.lower()
            for word in ("backup", "retention", "rpo", "rto", "recovery", "snapshot", "restore")
        ):
            continue
        claim = register.claim(finding.claim_id or "")
        out.append(
            {
                "subject": finding.subject,
                "observed": finding.observed or "",
                "asserted": claim.asserted if claim else "",
                "verdict": finding.verdict,
                "detail": finding.detail or "no source in the declared configuration",
                "evidence": f"{finding.evidence_file}:{finding.evidence_line or 1}",
            }
        )
    return sorted(out, key=lambda m: m["subject"])


# ---------------------------------------------------------------- exporting --


def export_pack(client: Any, pack: Pack, fmt: str = "pdf", session_id: str | None = None) -> bytes:
    """Through SuperDocs' renderer and house template. Free.

    Upload and export are both free operations, which is why this leans on them
    rather than shipping a PDF library. The document is uploaded as HTML — the
    same bytes the offline path writes — so the two outputs cannot drift.
    """
    session = session_id or client.init_session()
    client.upload(
        filename=f"{pack.title.lower().replace(' ', '-')}.html",
        content=pack.html,
        session_id=session,
        open_mode="new_focused",
    )
    return client.export_bytes(session_id=session, fmt=fmt)


# ------------------------------------------------------------------- markup --


def _document(title: str, parts: list[str]) -> str:
    """Plain semantic HTML, no stylesheet.

    The house format is the template's job on the SuperDocs side, and inline
    styling here would fight it. It also has to survive being read in a terminal
    with `w3m`, which is how somebody on call will actually read it.
    """
    return (
        f'<!DOCTYPE html>\n<html><head><meta charset="utf-8">'
        f"<title>{html.escape(title)}</title></head>\n<body>\n"
        + "\n".join(parts)
        + "\n</body></html>\n"
    )


def _h1(text: str) -> str:
    return f"<h1>{html.escape(text)}</h1>"


def _h2(text: str) -> str:
    return f"<h2>{html.escape(text)}</h2>"


def _p(text: str) -> str:
    # Already-escaped fragments are passed in deliberately (the <strong> above),
    # so this does not escape. Every caller escapes its own interpolations.
    return f"<p>{text}</p>"


def _list(items: Iterable[str]) -> str:
    return "<ul>" + "".join(f"<li>{html.escape(item)}</li>" for item in items) + "</ul>"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{html.escape(h)}</th>" for h in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{html.escape(str(cell))}</td>" for cell in row) + "</tr>"
        for row in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def _stat_table(pairs: list[tuple[str, str]]) -> str:
    return _table(["", ""], [[label, value] for label, value in pairs])


def _limits() -> str:
    """The same limitations in both documents, in the documents themselves.

    Not in a README somewhere. These get printed, forwarded and read a year
    later by somebody who never saw this repository, and a limitation that only
    exists in the tool's documentation is a limitation the reader does not have.
    """
    return _h2("How this was produced, and what it cannot tell you") + _list(
        [
            "Every line traces to a claim extracted from a document and checked against "
            "a file in the declared infrastructure repositories.",
            "It reads configuration committed to git, not the live state of any cloud "
            "account. A resource deleted by hand still appears declared.",
            "It checks what documents say against what configuration declares. Neither "
            "is evidence that a procedure works, or has ever been rehearsed.",
            "Claims it could not check are reported as unchecked and never as correct.",
            "No document was edited to produce this report.",
        ]
    )


def _now() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")


