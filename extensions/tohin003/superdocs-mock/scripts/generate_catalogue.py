#!/usr/bin/env python3
"""Generate the scenario catalogue from the cassettes themselves.

The card asks for a documented scenario catalogue. Writing one by hand would be the easy
version and the wrong one: a hand-written catalogue is a second source of truth that starts
drifting the first time a scenario is re-recorded, and it drifts silently because nothing
checks it.

So `docs/scenarios.md` is generated from what the mock will actually serve, and
`--check` fails CI when the committed file is stale. The catalogue cannot lie about the
fixtures because it is derived from them.

    python scripts/generate_catalogue.py
    python scripts/generate_catalogue.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from sdmock.replay import Library  # noqa: E402

OUT = ROOT / "docs" / "scenarios.md"

HEADER = """# Scenario catalogue

*Generated by `scripts/generate_catalogue.py` from the cassettes. Do not edit by hand.*

One mock covers many test cases. Pick a scenario with the `X-Mock-Scenario` header:

```bash
curl -H "Authorization: Bearer sk_test_anything" \\
     -H "X-Mock-Scenario: capacity-refusal" \\
     -X POST http://localhost:8080/v1/documents/upload
```

Over MCP, send the same header on the JSON-RPC request. If you cannot set headers at all
(`EventSource`, some MCP clients), set `SDMOCK_DEFAULT_SCENARIO` when starting the mock.

Two more headers are useful:

| Header | Effect |
|---|---|
| `X-Mock-Run: <id>` | An independent cursor, so two parallel runs of one scenario do not consume each other's job-state transitions. |
| `X-Mock-Latency: realistic` | Replay the recorded inter-event timings instead of firing instantly, to exercise a "still processing" UI against the real 30s-to-several-minute reality. |

`POST /__sdmock__/reset` rewinds every cursor. `GET /__sdmock__/catalogue` returns this
same information as JSON.

## How to read a scenario

**Recorded** scenarios were captured off `api.superdocs.app` against a synthetic corpus
authored for this repository. **Synthesised** ones were built from the documented shape
because they could not be observed responsibly — each says why, the mock sets
`X-Mock-Synthesised: true` on every response it serves from one, and the contract suite
skips them when it runs against the live service.

"""


def render(library: Library) -> str:
    rows = library.catalogue()
    recorded = [r for r in rows if not r["synthesised"]]
    synthesised = [r for r in rows if r["synthesised"]]

    out = [HEADER]
    out.append(f"**{len(rows)} scenarios — {len(recorded)} recorded, "
               f"{len(synthesised)} synthesised.** "
               f"Default when no header is sent: `{library.default_scenario()}`.\n")

    out.append("| Scenario | Kind | Endpoints | Behaviours |")
    out.append("|---|---|---|---|")
    for row in rows:
        kind = "synthesised" if row["synthesised"] else "recorded"
        endpoints = "<br>".join(f"`{e}`" for e in row["endpoints"])
        covers = ", ".join(row["covers"]) or "—"
        out.append(f"| **{row['scenario']}** | {kind} | {endpoints} | {covers} |")
    out.append("")

    for row in rows:
        out.append(f"### `{row['scenario']}`")
        out.append("")
        out.append(row["description"])
        out.append("")
        if row["synthesised"]:
            out.append(f"> **Synthesised, not recorded.** {row['synthesis_note']}")
            out.append("")
        else:
            out.append(f"*Recorded {row['recorded_at'][:10]} against "
                       f"`api.superdocs.app`.*")
            out.append("")
        out.append(f"Interactions: {row['interactions']}. "
                   f"Behaviours exercised: {', '.join(row['covers']) or 'none listed'}.")
        out.append("")
        first = row["endpoints"][0] if row["endpoints"] else None
        if first:
            method, path = first.split(" ", 1)
            demo = path.replace("{session_id}", "my-session") \
                       .replace("{job_id}", "my-job") \
                       .replace("{document_id}", "my-doc") \
                       .replace("{upload_id}", "my-upload")
            flag = "-X POST " if method == "POST" else ""
            out.append("```bash")
            out.append(f'curl {flag}-H "Authorization: Bearer sk_test_anything" \\')
            out.append(f'     -H "X-Mock-Scenario: {row["scenario"]}" \\')
            out.append(f'     http://localhost:8080{demo}')
            out.append("```")
            out.append("")

    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed catalogue is out of date")
    args = ap.parse_args()

    rendered = render(Library())

    if args.check:
        if not OUT.exists():
            print("docs/scenarios.md has never been generated", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != rendered:
            print("docs/scenarios.md is stale -- the cassettes have changed since it "
                  "was generated.\nRun: python scripts/generate_catalogue.py",
                  file=sys.stderr)
            return 1
        print("catalogue is up to date")
        return 0

    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
