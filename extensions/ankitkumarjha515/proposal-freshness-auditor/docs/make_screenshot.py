"""Render the README screenshot from a real run.

The screenshot is generated by running the actual commands and drawing
whatever they actually print. Nothing here types output by hand, so the
image cannot drift away from the tool as the tool changes. Regenerate with:

    python docs/make_screenshot.py

Requires pillow; it is a dev-only dependency and the tool itself never
imports it.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "screenshot.png"

BG = (13, 17, 23)
CHROME = (22, 27, 34)
FG = (201, 209, 217)
DIM = (110, 118, 129)
GREEN = (63, 185, 80)
RED = (248, 81, 73)
YELLOW = (210, 153, 34)
BLUE = (88, 166, 255)
PURPLE = (188, 140, 255)

FONT_PATH = r"C:\Windows\Fonts\consola.ttf"
FONT_BOLD = r"C:\Windows\Fonts\consolab.ttf"
SIZE = 20
PAD = 28
LINE_H = 26


def run(*args: str) -> str:
    """Run a CLI command and return exactly what it printed."""
    env = {**os.environ, "PYTHONPATH": "src", "PYTHONIOENCODING": "utf-8"}
    p = subprocess.run(
        [sys.executable, "-m", "freshness_auditor.cli", *args],
        cwd=ROOT, env=env, capture_output=True, text=True, encoding="utf-8",
    )
    return (p.stdout + p.stderr).replace("\r\n", "\n").rstrip("\n")


def prompt(cmd: str) -> list[tuple[str, tuple]]:
    return [(f"$ python -m freshness_auditor.cli {cmd}", BLUE)]


def colour(line: str) -> tuple:
    s = line.strip()
    if s.startswith("$"):
        return BLUE
    if "VERDICT" in line and "PASSED" in line:
        return GREEN
    if "LOW CONFIDENCE" in line or line.startswith("error:"):
        return YELLOW
    if s.startswith("finding(s)") or "finding(s):" in s:
        return FG
    if s.startswith("stale value"):
        return RED
    if s.startswith(("should be", "byte-identical")) or "byte-identical" in line:
        return GREEN
    if s.startswith(("per ", "match ", "location", "context", "note ")):
        return DIM
    if s.startswith("["):
        return PURPLE
    return FG


def keep(text: str, first: int, last: int = 0) -> list[str]:
    lines = text.split("\n")
    if last and len(lines) > first + last:
        return lines[:first] + ["    ..."] + lines[-last:]
    return lines


def main() -> None:
    (ROOT / "findings.json").unlink(missing_ok=True)

    audit = run("audit")
    # Two findings tell the whole story: an exact hit and a paraphrase that
    # no substring search would ever find.
    blocks: list[str] = []
    blocks += prompt("audit")[0][0].split("\n")
    lines = audit.split("\n")
    blocks += lines[:9]
    blocks += ["    ..."]
    # the paraphrase finding
    for n, ln in enumerate(lines):
        if "twelve hundred" in ln and ln.strip().startswith("stale value"):
            blocks += lines[n - 1: n + 8]
            break
    blocks += ["    ...", lines[-3], ""]

    # Each command's own output goes under its own prompt. Anything else
    # would be a staged screenshot, which is the one thing this tool exists
    # to argue against.
    for cmd, args in [
        ("review --approve 1 2 3 4 6 7 8",
         ["review", "--approve", "1", "2", "3", "4", "6", "7", "8"]),
        ("review --reject 5 --note 'confidence too low - verify by hand'",
         ["review", "--reject", "5", "--note",
          "confidence too low - verify by hand"]),
        ("apply --fake", ["apply", "--fake"]),
    ]:
        blocks += prompt(cmd)[0][0].split("\n")
        blocks += run(*args).split("\n")
        blocks += [""]
    blocks.pop()

    font = ImageFont.truetype(FONT_PATH, SIZE)
    bold = ImageFont.truetype(FONT_BOLD, SIZE)

    width = PAD * 2 + max(int(font.getlength(b)) for b in blocks) + 20
    height = PAD * 2 + LINE_H * len(blocks) + 44

    img = Image.new("RGB", (width, height), BG)
    d = ImageDraw.Draw(img)

    d.rectangle([0, 0, width, 44], fill=CHROME)
    for n, c in enumerate([(255, 95, 86), (255, 189, 46), (39, 201, 63)]):
        d.ellipse([PAD + n * 26, 15, PAD + n * 26 + 14, 29], fill=c)
    title = "proposal boilerplate freshness auditor"
    d.text(((width - font.getlength(title)) / 2, 12), title, font=font, fill=DIM)

    y = 44 + PAD
    for line in blocks:
        f = bold if line.strip().startswith("$") or "VERDICT" in line else font
        d.text((PAD, y), line, font=f, fill=colour(line))
        y += LINE_H

    OUT.parent.mkdir(parents=True, exist_ok=True)
    img.save(OUT)
    print(f"wrote {OUT}  ({width}x{height})")


if __name__ == "__main__":
    main()
