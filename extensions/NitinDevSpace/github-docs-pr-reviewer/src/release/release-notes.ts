import type {
  ComparedFile,
  GitHubReleaseClient,
  ReleaseTarget
} from "../github/release-client.js";
import { escapeHtml, markdownToSafeHtml } from "../preview/markdown-html.js";
import { isDocumentationPath } from "../review/scanner.js";

export type ReleaseDocumentSources = {
  target: ReleaseTarget;
  previousTag?: string;
  changelog: string;
  documentationChanges: ComparedFile[];
  /** Anything the collector could not determine, stated rather than hidden. */
  notes: string[];
};

/**
 * Gathers what the release document can honestly say.
 *
 * Everything beyond the release body is best-effort: if GitHub cannot tell us the
 * previous tag or the file list, the document says so instead of leaving a
 * confident-looking empty section.
 */
export async function collectReleaseSources({
  client,
  target
}: {
  client: GitHubReleaseClient;
  target: ReleaseTarget;
}): Promise<ReleaseDocumentSources> {
  const notes: string[] = [];
  const changelog = target.body?.trim() ?? "";

  if (changelog === "") {
    notes.push("This release was published without release notes.");
  }

  let previousTag: string | undefined;

  try {
    previousTag = findPreviousTag(
      await client.listReleases({ owner: target.owner, repo: target.repo }),
      target
    );
  } catch (error) {
    notes.push(
      `The previous release could not be determined (${describeError(error)}), so documentation changes are not listed.`
    );
    return { target, changelog, documentationChanges: [], notes };
  }

  if (!previousTag) {
    notes.push(
      "No earlier published release was found, so this document lists no documentation diff."
    );
    return { target, changelog, documentationChanges: [], notes };
  }

  try {
    const compared = await client.compareRefs({
      owner: target.owner,
      repo: target.repo,
      base: previousTag,
      head: target.tagName
    });

    const documentationChanges = compared.filter((file) =>
      isDocumentationPath(file.path)
    );

    if (documentationChanges.length === 0) {
      notes.push(
        `No documentation files changed between \`${previousTag}\` and \`${target.tagName}\`.`
      );
    }

    return { target, previousTag, changelog, documentationChanges, notes };
  } catch (error) {
    notes.push(
      `Documentation changes since \`${previousTag}\` could not be listed (${describeError(error)}).`
    );
    return { target, previousTag, changelog, documentationChanges: [], notes };
  }
}

export function releaseDocumentTitle(target: ReleaseTarget): string {
  const label = target.name?.trim() || target.tagName;
  return `${target.owner}/${target.repo} — ${label}`;
}

export function renderReleaseDocumentHtml(
  sources: ReleaseDocumentSources
): string {
  const { target } = sources;
  const title = releaseDocumentTitle(target);
  const published = formatPublishedDate(target.publishedAt);

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>${escapeHtml(title)}</title>
  <style>
    :root { color-scheme: light; font-family: Inter, ui-sans-serif, system-ui, sans-serif; }
    body { margin: 0; color: #202124; background: #ffffff; line-height: 1.6; }
    main { max-width: 820px; margin: 0 auto; padding: 56px 32px; }
    .brand { text-transform: uppercase; letter-spacing: .14em; font-size: 12px; color: #5f6368; }
    h1 { font-size: 30px; line-height: 1.2; margin: 6px 0 4px; }
    .meta { color: #5f6368; font-size: 14px; margin: 0 0 32px; }
    h2 { font-size: 18px; margin: 32px 0 10px; border-bottom: 1px solid #dadce0; padding-bottom: 6px; }
    table { width: 100%; border-collapse: collapse; font-size: 14px; }
    th, td { text-align: left; padding: 8px 10px; border-bottom: 1px solid #e8eaed; }
    th { color: #5f6368; font-weight: 600; }
    code { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; font-size: 13px; }
    pre { background: #f1f3f4; padding: 14px; overflow-x: auto; }
    .notes { background: #f8f9fa; border-left: 3px solid #dadce0; padding: 12px 16px; font-size: 14px; }
    footer { margin-top: 48px; border-top: 2px solid #202124; padding-top: 14px; color: #5f6368; font-size: 12px; }
  </style>
</head>
<body><main>
  <p class="brand">Release documentation</p>
  <h1>${escapeHtml(title)}</h1>
  <p class="meta">Tag <code>${escapeHtml(target.tagName)}</code>${published ? ` · Published ${escapeHtml(published)}` : ""}${sources.previousTag ? ` · Changes since <code>${escapeHtml(sources.previousTag)}</code>` : ""}</p>

  <h2>Release notes</h2>
  ${sources.changelog ? markdownToSafeHtml(sources.changelog) : "<p><em>No release notes were provided for this release.</em></p>"}

  <h2>Documentation changed in this release</h2>
  ${renderDocumentationTable(sources.documentationChanges)}

  ${renderNotes(sources.notes)}

  <footer>
    Generated by the SuperDocs docs PR reviewer from this repository's release notes and file history.
    Content is reproduced from the release; it is not independently verified.
  </footer>
</main></body>
</html>`;
}

function renderDocumentationTable(files: ComparedFile[]): string {
  if (files.length === 0) {
    return "<p><em>No documentation files are listed for this release.</em></p>";
  }

  const rows = files
    .map(
      (file) =>
        `    <tr><td><code>${escapeHtml(file.path)}</code></td><td>${escapeHtml(file.status)}</td></tr>`
    )
    .join("\n");

  return `<table>
  <thead><tr><th>File</th><th>Change</th></tr></thead>
  <tbody>
${rows}
  </tbody>
</table>`;
}

function renderNotes(notes: string[]): string {
  if (notes.length === 0) return "";

  const items = notes
    .map((note) => `    <li>${markdownToSafeHtml(note).replace(/^<p>|<\/p>\s*$/g, "")}</li>`)
    .join("\n");

  return `<h2>What this document could not determine</h2>
  <div class="notes"><ul>
${items}
  </ul></div>`;
}

function findPreviousTag(
  releases: Array<{
    id: number;
    tagName: string;
    publishedAt?: string;
    draft?: boolean;
    prerelease?: boolean;
  }>,
  target: ReleaseTarget
): string | undefined {
  const current = releases.find((release) => release.id === target.releaseId);
  const currentPublishedAt = current?.publishedAt ?? target.publishedAt;

  const candidates = releases
    .filter((release) => release.id !== target.releaseId)
    .filter((release) => release.draft !== true)
    .filter((release) => release.tagName !== target.tagName)
    .filter((release) => release.publishedAt !== undefined)
    .filter((release) =>
      currentPublishedAt ? release.publishedAt! < currentPublishedAt : true
    )
    .sort((a, b) => b.publishedAt!.localeCompare(a.publishedAt!));

  return candidates[0]?.tagName;
}

function formatPublishedDate(publishedAt?: string): string | undefined {
  if (!publishedAt) return undefined;

  const date = new Date(publishedAt);
  if (Number.isNaN(date.getTime())) return undefined;

  return date.toISOString().slice(0, 10);
}

function describeError(error: unknown): string {
  return error instanceof Error ? error.message : "unknown error";
}
